function BizItem({
  no,
  title,
  children,
  rows,
}: {
  no: string;
  title: string;
  children: ReactNode;
  rows: [string, string][];
}) {
  return (
    <div className="biz-i">
      <div className="no">{no}</div>
      <h4>{title}</h4>
      <p>{children}</p>
      <dl>
        {rows.map(([dt, dd]) => (
          <div className="rw" key={dt}>
            <dt>{dt}</dt>
            <dd>{dd}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}


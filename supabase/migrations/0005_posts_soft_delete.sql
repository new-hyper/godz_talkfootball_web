-- 글을 지울 수 있게 고친다
--
-- 0004 를 올리고 나서 침투 시험을 해 보니 소프트 삭제만 되지 않았다.
-- 본인 글인데도 deleted_at 을 적으려 하면 이렇게 거절당했다.
--
--   new row violates row-level security policy for table "posts"
--
-- 제목·본문 수정은 같은 정책을 지나서 잘 됐다. deleted_at 일 때만 걸렸다.
--
-- 이유는 이렇다. Supabase 의 REST 계층은 수정 요청을 처리할 때
-- 몇 줄이 바뀌었는지 세려고 방금 바꾼 행을 되읽는다. 그때 읽기 정책이 적용된다.
-- 그런데 우리가 쓴 읽기 정책은 지워진 글을 아무에게도 보여주지 않았다.
-- 그러니 방금 지운 그 행을 자기가 못 읽는 상황이 되고, 그래서 통째로 거부된 것이다.
--
-- "지운 글은 아무도 못 본다" 가 너무 세서 지우는 행위 자체를 막은 셈이다.
--
-- 그래서 "내가 쓴 글은 지워졌어도 내가 읽을 수 있다" 를 더한다.
-- 자기가 쓴 글이니 본인이 보는 것은 문제가 아니고,
-- 다른 사람에게는 여전히 안 보인다.
--
-- 목록과 상세는 posts_view 가 그리고 그 뷰에는 따로 조건이 걸려 있으므로
-- 지운 글이 화면에 도로 나타나지는 않는다. 여기서 넓히는 것은
-- 글 표를 직접 건드리는 길, 즉 쓰기·수정·삭제 경로뿐이다.
--
-- 한 번 지운 글을 되살리는 것은 여전히 막혀 있다.
-- posts_guard_update 가 old.deleted_at 이 이미 차 있으면 못 바꾸게 한다.

drop policy "지워지지 않은 글은 누구나 읽는다" on public.posts;

create policy "지워지지 않은 글은 누구나 읽는다"
  on public.posts for select
  using (
    deleted_at is null
    or public.is_admin()
    -- 지워진 글은 쓴 사람만 더 본다. 지우는 요청이 스스로 막히지 않게 하려는 것이다.
    or author_uid = (select auth.uid())
  );
